// Ohne Namen ist das Symbol Schmuck (aria-hidden). Mit title oder
// aria-label wird es ein benanntes Bild (Audit 23.09.2026, WP12-F07): Vorher
// kannte der Typ nur title, ein übergebenes aria-label fiel still weg. Die
// übrigen SVG-Attribute laufen durch, damit der Typ solche Fehler meldet.
export function Icon({
  name,
  size = 16,
  className,
  title,
  ...rest
}: {
  name: IconName
  size?: number
  className?: string
  title?: string
} & Omit<ComponentProps<'svg'>, 'name' | 'title' | 'children'>) {
  const label = rest['aria-label'] ?? title
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.9}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...rest}
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      className={`shrink-0 ${className ?? ''}`}
    >
      {GLYPHS[name]}
    </svg>
  )
}
